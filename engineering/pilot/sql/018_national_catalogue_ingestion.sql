CREATE FUNCTION identity.has_catalogue_review_capability(p_actor UUID, p_capability TEXT)
RETURNS BOOLEAN LANGUAGE SQL STABLE SECURITY DEFINER
SET search_path = pg_catalog, identity
SET row_security = off
AS $$ SELECT EXISTS (
    SELECT 1 FROM identity.catalogue_review_grants g
    WHERE g.user_id = p_actor AND g.capability = p_capability AND g.revoked_at IS NULL
) $$;
REVOKE ALL ON FUNCTION identity.has_catalogue_review_capability(UUID,TEXT) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION identity.has_catalogue_review_capability(UUID,TEXT) TO ai_tourism_app;
CREATE FUNCTION identity.current_app_actor_id() RETURNS UUID
LANGUAGE SQL STABLE
SET search_path = pg_catalog
AS $$ SELECT NULLIF(current_setting('app.actor_id', true), '')::uuid $$;
