/** Map backend codes to reviewed UI copy without exposing entity IDs or tag text. */
export function localizeRecommendationCode(locale: Locale, code: string): string {
  if (/^destination:\d+$/.test(code)) return recommendationCodeMessages[locale].selected_area_match;
  if (code.startsWith('interest:') && code.length > 'interest:'.length) {
    return recommendationCodeMessages[locale].exact_interest_tag_match;
  }
  return recommendationCodeMessages[locale][code] ?? journeyMessages[locale].unknown;
}
